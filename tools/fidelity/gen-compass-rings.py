#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate assets/map/compass-rings.json from app/mechanics.json (唯一数字真相源).

Why this exists: M7 A 路线把盘面绘制搬进 map.html 的 canvas，JS 需要圈层/盘面/字表数据。
硬规矩（技术总监 M6 已批）：**唯一真相源是 `app/mechanics.json`，JS 不许手抄第二份。**
本脚本只做「同一份数据的搬运与裁剪」，不产生任何新数值；输出里记录源文件 sha256，
供 assets 门禁与 L2 基线复核。

用法：
    python tools/fidelity/gen-compass-rings.py
    python tools/fidelity/gen-compass-rings.py --check   # 只校验输出是否与源一致
"""
import argparse
import hashlib
import io
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'app', 'mechanics.json')
DST = os.path.join(ROOT, 'app', 'android', 'app', 'src', 'main', 'assets', 'map', 'compass-rings.json')


def load_source():
    raw = open(SRC, 'rb').read()
    return json.loads(raw.decode('utf-8')), hashlib.sha256(raw).hexdigest()


def build(src, sha):
    rings = []
    for r in src.get('rings', []):
        rings.append({
            'id': r.get('id'),
            'type': r.get('type'),
            'text': r.get('text'),
            'interval': r.get('interval'),
            'offset': r.get('offset'),
            'labels': r.get('labels', []),
        })
    dials = []
    for d in src.get('dials', []):
        dials.append({
            'id': d.get('id'),
            'text': d.get('text'),
            'vip': bool(d.get('vip')),
            'rings': d.get('rings', d.get('rings_status', [])),
        })
    return {
        'schema': 1,
        'source': 'app/mechanics.json',
        'source_sha256': sha,
        'note': 'Generated by tools/fidelity/gen-compass-rings.py — do not hand edit.',
        'dials': dials,
        'rings': rings,
        'tables': src.get('tables', {}),
        'plates': src.get('plates', {}),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='verify the committed file matches the source')
    a = ap.parse_args()

    src, sha = load_source()
    want = json.dumps(build(src, sha), ensure_ascii=False, indent=1, sort_keys=False) + '\n'

    if a.check:
        if not os.path.exists(DST):
            print('[FAIL] missing %s' % DST)
            return 1
        have = io.open(DST, encoding='utf-8').read()
        if have != want:
            print('[FAIL] compass-rings.json is stale vs app/mechanics.json (sha %s)' % sha[:16])
            return 1
        print('[PASS] compass-rings.json matches mechanics.json sha %s' % sha[:16])
        return 0

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    io.open(DST, 'w', encoding='utf-8', newline='\n').write(want)
    data = io.open(DST, 'rb').read()
    print('[PASS] wrote %s' % os.path.relpath(DST, ROOT))
    print('       source_sha256=%s' % sha)
    print('       dials=%d rings=%d tables=%d bytes=%d sha256=%s' % (
        len(src.get('dials', [])), len(src.get('rings', [])), len(src.get('tables', {})),
        len(data), hashlib.sha256(data).hexdigest()[:16]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
