#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate assets/map/compass-rings.json from app/mechanics.json (唯一数字真相源).

Why this exists: M7 A 路线把盘面绘制搬进 map.html 的 canvas，JS 需要圈层/盘面/字表数据。
硬规矩（技术总监 M6 已批）：**唯一真相源是 `app/mechanics.json`，JS 不许手抄第二份。**
本脚本只做「同一份数据的搬运与裁剪」，不产生任何新数值；输出里记录源文件 sha256，
供 assets 门禁与 L2 基线复核。

用法：
    python tools/fidelity/gen-compass-rings.py
    python tools/fidelity/gen-compass-rings.py --check   # 只校验输出是否与源一致
"""
import argparse
import hashlib
import io
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'app', 'mechanics.json')
DST = os.path.join(ROOT, 'app', 'android', 'app', 'src', 'main', 'assets', 'map', 'compass-rings.json')
# 运行时副本（11-08 定）：WebView 页面源是 file:///android_asset/，Chromium 的 Fetch API 与 XHR
# 都拒绝 file 方案（审核验实测："URL scheme \"file\" is not supported"），JSON 读不进来。
# 因此同一份数据再输出一个 <script> 可加载的 JS（script 标签不受该限制），
# map.html 优先读 window.__LC_COMPASS_RINGS，fetch/XHR 仅作后备。
DST_JS = os.path.join(ROOT, 'app', 'android', 'app', 'src', 'main', 'assets', 'map', 'compass-rings.js')


def load_source():
    raw = open(SRC, 'rb').read()
    return json.loads(raw.decode('utf-8')), hashlib.sha256(raw).hexdigest()


def build(src, sha):
    rings = []
    for r in src.get('rings', []):
        rings.append({
            'id': r.get('id'),
            'type': r.get('type'),
            'text': r.get('text'),
            'interval': r.get('interval'),
            'offset': r.get('offset'),
            'labels': r.get('labels', []),
        })
    # 注意：mechanics.json 里 dials[] **没有** `rings` 键。`rings_status` 是一句状态描述
    # （"dial_is_full_artwork_image__no_per_dial_ring_set"），说明"盘面用整张图、不按盘分配环"。
    # 曾把它塞进 `rings` 字段：值是**字符串**，下游按数组遍历会拿到一串字符 —— 已改为原名保留，
    # 并且**不再**伪造 `rings` 键；圈层数据一律只从顶层 `rings`（14 条）取。
    dials = []
    for d in src.get('dials', []):
        dials.append({
            'id': d.get('id'),
            'text': d.get('text'),
            'vip': bool(d.get('vip')),
            'rings_status': d.get('rings_status'),
        })
    return {
        'schema': 1,
        'source': 'app/mechanics.json',
        'source_sha256': sha,
        'note': 'Generated by tools/fidelity/gen-compass-rings.py — do not hand edit.',
        'dials': dials,
        'rings': rings,
        'tables': src.get('tables', {}),
        'plates': src.get('plates', {}),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='verify the committed file matches the source')
    a = ap.parse_args()

    src, sha = load_source()
    want = json.dumps(build(src, sha), ensure_ascii=False, indent=1, sort_keys=False) + '\n'
    # JS 副本：同一份 JSON，包成全局常量；首行注释带源 sha，便于反查是哪个 mechanics.json 生成的
    want_js = ('/* generated by tools/fidelity/gen-compass-rings.py — do not edit.\n'
               ' * source: app/mechanics.json sha256=%s */\n'
               'window.__LC_COMPASS_RINGS = %s;\n') % (sha, json.dumps(build(src, sha), ensure_ascii=False, separators=(',', ':')))

    if a.check:
        bad = 0
        for path, content in ((DST, want), (DST_JS, want_js)):
            rel = os.path.relpath(path, ROOT)
            if not os.path.exists(path):
                print('[FAIL] missing %s' % rel)
                bad = 1
            elif io.open(path, encoding='utf-8').read() != content:
                print('[FAIL] %s is stale vs app/mechanics.json (sha %s)' % (rel, sha[:16]))
                bad = 1
        if bad:
            return 1
        print('[PASS] compass-rings.json / compass-rings.js match mechanics.json sha %s' % sha[:16])
        return 0

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    io.open(DST, 'w', encoding='utf-8', newline='\n').write(want)
    io.open(DST_JS, 'w', encoding='utf-8', newline='\n').write(want_js)
    data = io.open(DST, 'rb').read()
    print('[PASS] wrote %s (%d B)' % (os.path.relpath(DST, ROOT), len(data)))
    print('[PASS] wrote %s (%d B)' % (os.path.relpath(DST_JS, ROOT), len(want_js.encode('utf-8'))))
    print('       source_sha256=%s' % sha)
    print('       dials=%d rings=%d tables=%d bytes=%d sha256=%s' % (
        len(src.get('dials', [])), len(src.get('rings', [])), len(src.get('tables', {})),
        len(data), hashlib.sha256(data).hexdigest()[:16]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
